/** Exact v1 formula: +40% rounded to nearest 10, minimum +50 ₽ */
export function calcOldPrice(price: number): number | null {
  if (!price || price <= 0) return null;
  return Math.max(Math.round((price * 1.4) / 10) * 10, Math.round(price + 50));
}

/** Exact v1 GS1 EAN-13 generator from DP-B-XXXXX article (prefix 297847) */
export function generateEan13FromArticle(article: string): string {
  const digitsOnly = (article || "").replace(/\D/g, "");
  const num = Math.max(1, parseInt(digitsOnly || "1", 10) || 1);
  const base12 = `297847${String(num).padStart(6, "0")}`.slice(-12);
  let sum = 0;
  for (let i = 0; i < 12; i++) {
    sum += Number(base12[i]) * (i % 2 === 0 ? 1 : 3);
  }
  const check = (10 - (sum % 10)) % 10;
  return `${base12}${check}`;
}
